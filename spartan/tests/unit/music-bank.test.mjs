// The pre-rendered music: the generated bank (js/audio/musicbank.js) against the Ogg Opus loops on disk
// (audio/music/*.ogg) and the briefs in spartan/tools/music/cues.json. Guards against a cue re-rendered
// without regenerating the bank (or the reverse), a hand-edited bank, a loop that no longer lands on whole
// 20 ms Opus frames, a cue over the true-peak ceiling, and the music's memory and download budgets.
// node --test spartan/tests/unit/music-bank.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MUSICBANK } from '../../src/main/assets/game/js/audio/musicbank.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const GAME = path.resolve(HERE, '../../src/main/assets/game');
const MUSIC_DIR = path.join(GAME, 'audio/music');
const CUES = JSON.parse(fs.readFileSync(path.resolve(HERE, '../../tools/music/cues.json'), 'utf8'));
const CUE_NAMES = Object.keys(CUES).filter((k) => !k.startsWith('_'));
const SR = 48000;

// Budgets (spartan/tools/music/README.md, "Notes for the game"). A cue decodes to a 48 kHz stereo float32
// AudioBuffer of samples x 2 x 4 bytes; the game holds the playing cue and, during a crossfade, the one
// fading out, never all three.
const CEILING_DBTP = -1.5;
const MAX_FILES_BYTES = 4 * 1048576; // the three .ogg files in the APK
const MAX_DECODED_BYTES = 48e6; // one decoded cue (battle, 120 s: 46 080 000 B)
const MAX_CROSSFADE_BYTES = 90e6; // the two largest cues at once (battle + lastStand: 87 859 200 B)

// Ogg's CRC-32 (polynomial 0x04C11DB7, not reflected, initial value 0).
const CRC = new Uint32Array(256);
for (let i = 0; i < 256; i++) {
  let r = i << 24;
  for (let k = 0; k < 8; k++) r = r & 0x80000000 ? (r << 1) ^ 0x04c11db7 : r << 1;
  CRC[i] = r >>> 0;
}
function oggCrc(page) {
  let c = 0;
  for (let i = 0; i < page.length; i++) c = ((c << 8) ^ CRC[((c >>> 24) ^ page[i]) & 255]) >>> 0;
  return c;
}

/** An Ogg Opus file's pages: { head, tags, preSkip, channels, version, rate, lastGranule, eos, pages }. */
function oggOpus(buf, where) {
  const out = { pages: 0, lastGranule: -1n, eos: false, head: null, tags: null };
  let pos = 0, cur = [];
  const packets = [];
  while (pos < buf.length) {
    assert.equal(buf.toString('latin1', pos, pos + 4), 'OggS', `${where}: Ogg page magic at byte ${pos}`);
    const flags = buf[pos + 5];
    const granule = buf.readBigInt64LE(pos + 6);
    const crc = buf.readUInt32LE(pos + 22);
    const segs = buf[pos + 26];
    let body = 0;
    for (let i = 0; i < segs; i++) body += buf[pos + 27 + i];
    const end = pos + 27 + segs + body;
    const page = Buffer.from(buf.subarray(pos, end));
    page.writeUInt32LE(0, 22);
    assert.equal(oggCrc(page), crc, `${where}: CRC of Ogg page ${out.pages}`);
    let d = pos + 27 + segs;
    for (let i = 0; i < segs && packets.length < 2; i++) {
      const len = buf[pos + 27 + i];
      cur.push(buf.subarray(d, d + len));
      d += len;
      if (len < 255) { packets.push(Buffer.concat(cur)); cur = []; }
    }
    if (granule >= 0n) out.lastGranule = granule;
    out.eos = !!(flags & 4);
    out.pages++;
    pos = end;
  }
  assert.equal(pos, buf.length, `${where}: the last page ends at the end of the file`);
  const [head, tags] = packets;
  assert.equal(head.toString('latin1', 0, 8), 'OpusHead', `${where}: OpusHead`);
  out.version = head[8];
  out.channels = head[9];
  out.preSkip = head.readUInt16LE(10);
  out.rate = head.readUInt32LE(12);
  assert.equal(tags.toString('latin1', 0, 8), 'OpusTags', `${where}: OpusTags`);
  out.tags = {};
  let p = 8;
  p += 4 + tags.readUInt32LE(p);
  const count = tags.readUInt32LE(p);
  p += 4;
  for (let i = 0; i < count; i++) {
    const len = tags.readUInt32LE(p);
    const s = tags.toString('utf8', p + 4, p + 4 + len);
    const eq = s.indexOf('=');
    out.tags[s.slice(0, eq).toUpperCase()] = s.slice(eq + 1);
    p += 4 + len;
  }
  return out;
}

/** Quarter notes in a loop from its METER map ('4/4' or e.g. '4/4,5/4@21,4/4@29') and BARS. */
function quarterNotes(meter, bars) {
  const sigs = meter.split(',').map((part, i) => {
    const [sig, at] = part.split('@');
    const [num, den] = sig.split('/').map(Number);
    return { bar: at ? Number(at) : 1, num, den, i };
  });
  assert.equal(sigs[0].bar, 1, `meter map ${meter} starts at bar 1`);
  let q = 0;
  for (let b = 1; b <= bars; b++) {
    const s = sigs.filter((x) => x.bar <= b).pop();
    q += (4 * s.num) / s.den;
  }
  return q;
}

test('the bank is frozen generated data covering exactly the cues of cues.json', () => {
  const src = fs.readFileSync(path.join(GAME, 'js/audio/musicbank.js'), 'utf8');
  assert.ok(src.startsWith('// GENERATED by spartan/tools/music/render.mjs. Do not edit by hand.\n'));
  assert.ok(Object.isFrozen(MUSICBANK));
  assert.deepEqual(Object.keys(MUSICBANK).sort(), [...CUE_NAMES].sort());
  for (const e of Object.values(MUSICBANK)) {
    assert.ok(Object.isFrozen(e));
    assert.deepEqual(Object.keys(e), ['file', 'dur', 'samples', 'bpm', 'lufs']);
  }
  // Nothing in audio/music that the bank does not play (it would only bloat the APK).
  const used = new Set(Object.values(MUSICBANK).map((e) => path.basename(e.file)));
  assert.deepEqual(fs.readdirSync(MUSIC_DIR).filter((f) => !used.has(f)), [], 'unused files in audio/music');
});

test('every cue is a seamless stereo Ogg Opus loop whose length, tempo and loudness match the bank', () => {
  for (const [cue, e] of Object.entries(MUSICBANK)) {
    assert.equal(e.file, `audio/music/${cue}.ogg`, `${cue}: file`);
    const full = path.join(GAME, e.file);
    assert.ok(fs.existsSync(full), `${cue}: ${e.file} is missing`);
    const o = oggOpus(fs.readFileSync(full), cue);
    assert.equal(o.version, 1, `${cue}: OpusHead version`);
    assert.equal(o.channels, 2, `${cue}: stereo`);
    assert.equal(o.rate, SR, `${cue}: encoded from 48 kHz`);
    assert.ok(o.eos, `${cue}: the last page carries EOS`);
    const len = Number(o.lastGranule - BigInt(o.preSkip));
    assert.equal(len, e.samples, `${cue}: the file decodes to ${len} samples, the bank says ${e.samples}`);
    assert.equal(Math.round(e.dur * SR), e.samples, `${cue}: dur ${e.dur} s vs samples ${e.samples}`);
    assert.equal(Number(o.tags.LOOPLENGTH), e.samples, `${cue}: LOOPLENGTH tag`);
    assert.equal(Number(o.tags.LOOPSTART), 0, `${cue}: LOOPSTART tag`);
    assert.equal(e.samples % 960, 0, `${cue}: the loop is whole 20 ms Opus frames (a packet loop)`);
    assert.equal(o.tags.LOOPMODE, 'packet-loop', `${cue}: LOOPMODE`);
    const [lo, hi] = CUES[cue].loopSeconds;
    assert.ok(e.dur >= lo && e.dur <= hi, `${cue}: ${e.dur} s outside the brief's ${lo}-${hi} s`);
    if (CUES[cue].bpm) assert.ok(e.bpm >= CUES[cue].bpm[0] && e.bpm <= CUES[cue].bpm[1], `${cue}: bpm ${e.bpm}`);
    assert.equal(Number(o.tags.BPM), e.bpm, `${cue}: BPM tag`);
    // The bar grid (METER map, BARS, BEATS at BPM) adds up to the loop.
    const q = quarterNotes(o.tags.METER, Number(o.tags.BARS));
    assert.equal(q, Number(o.tags.BEATS), `${cue}: BEATS tag vs METER ${o.tags.METER} x BARS ${o.tags.BARS}`);
    assert.equal(Math.round((q * 60 / e.bpm) * SR), e.samples, `${cue}: ${q} quarter notes at ${e.bpm} bpm vs ${e.samples} samples`);
    assert.ok(Math.abs(Number(o.tags.LUFS) - e.lufs) <= 0.05, `${cue}: LUFS tag ${o.tags.LUFS} vs bank ${e.lufs}`);
    // TRUEPEAK_DBTP is the decoded file's true peak (master.py measures it after encoding).
    assert.ok(Number.isFinite(Number(o.tags.TRUEPEAK_DBTP)), `${cue}: TRUEPEAK_DBTP tag`);
    assert.ok(Number(o.tags.TRUEPEAK_DBTP) <= CEILING_DBTP, `${cue}: true peak ${o.tags.TRUEPEAK_DBTP} dBTP over ${CEILING_DBTP}`);
  }
  // One common level, so a crossfade does not jump.
  const lufs = Object.values(MUSICBANK).map((e) => e.lufs);
  assert.ok(Math.max(...lufs) - Math.min(...lufs) <= 0.5, `loudness spread ${lufs.join(', ')}`);
});

test('the music stays inside its download and memory budgets', () => {
  const entries = Object.values(MUSICBANK);
  const bytes = entries.reduce((s, e) => s + fs.statSync(path.join(GAME, e.file)).size, 0);
  assert.ok(bytes <= MAX_FILES_BYTES, `audio/music is ${bytes} bytes`);
  const decoded = entries.map((e) => e.samples * 2 * 4).sort((a, b) => b - a);
  assert.ok(decoded[0] <= MAX_DECODED_BYTES, `the largest cue decodes to ${decoded[0]} bytes`);
  assert.ok(decoded[0] + (decoded[1] || 0) <= MAX_CROSSFADE_BYTES, `a crossfade holds ${decoded[0] + decoded[1]} bytes`);
});
