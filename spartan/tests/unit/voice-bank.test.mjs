// (audio/voicebank.js) against the clips on disk and the campaign's VOICE table (§13).
// node --test spartan/tests/unit/voice-bank.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pickVoiceLine, variantCount, clipFiles } from '../../src/main/assets/game/js/audio/voicelines.js';
import { VOICEBANK } from '../../src/main/assets/game/js/audio/voicebank.js';
import { VOICE, LEONIDAS_BATTLE_LINES } from '../../src/main/assets/game/js/game/campaign.js';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../src/main/assets/game');
const VOICE_DIR = path.join(GAME, 'audio/voice');

/** Pages of an Ogg stream: { preSkip, channels, version, lastGranule, head, tags, pages }. */
function oggOpus(buf) {
  const out = { pages: 0, preSkip: -1, channels: 0, version: 0, lastGranule: -1n, head: false, tags: false };
  let pos = 0;
  while (pos < buf.length) {
    assert.equal(buf.toString('latin1', pos, pos + 4), 'OggS', `Ogg page magic at byte ${pos}`);
    const granule = buf.readBigInt64LE(pos + 6);
    const segs = buf[pos + 26];
    let body = 0;
    for (let i = 0; i < segs; i++) body += buf[pos + 27 + i];
    const data = pos + 27 + segs;
    if (out.pages === 0) {
      out.head = buf.toString('latin1', data, data + 8) === 'OpusHead';
      out.version = buf[data + 8];
      out.channels = buf[data + 9];
      out.preSkip = buf.readUInt16LE(data + 10);
    } else if (out.pages === 1) {
      out.tags = buf.toString('latin1', data, data + 8) === 'OpusTags';
    }
    if (granule >= 0n) out.lastGranule = granule;
    out.pages++;
    pos = data + body;
  }
  assert.equal(pos, buf.length, 'the last page ends at the end of the file');
  return out;
}

/** Every bank clip as { key, i, speaker, greek, en, file, dur }. */
function allClips() {
  const out = [];
  for (const [key, list] of Object.entries(VOICEBANK)) {
    list.forEach((v, i) => {
      for (const [speaker, c] of Object.entries(v.clips)) out.push({ key, i, speaker, greek: v.greek, en: v.en, file: c.file, dur: c.dur });
    });
  }
  return out;
}

/** Who can say each line: its VOICE speaker, and Dienekes for the king's battle lines once he has fallen. */
function speakersOf(key) {
  const s = [VOICE[key].speaker];
  if (LEONIDAS_BATTLE_LINES.includes(key)) s.push('Dienekes');
  return s;
}

test('pickVoiceLine cycles through the variants a speaker has a clip for', () => {
  const bank = {
    a: [
      { greek: 'Α', en: 'a1', clips: { X: { file: 'a1x.ogg', dur: 1 }, Y: { file: 'a1y.ogg', dur: 1.1 } } },
      { greek: 'Β', en: 'a2', clips: { X: { file: 'a2x.ogg', dur: 2 } } },
      { greek: 'Γ', en: 'a3', clips: { X: { file: 'a3x.ogg', dur: 3 }, Y: { file: 'a3y.ogg', dur: 3.1 } } },
    ],
  };
  assert.deepEqual([0, 1, 2, 3, 4].map((n) => pickVoiceLine(bank, 'a', 'X', n).file), ['a1x.ogg', 'a2x.ogg', 'a3x.ogg', 'a1x.ogg', 'a2x.ogg']);
  // Y has no clip of the second variant: he alternates between the other two.
  assert.deepEqual([0, 1, 2].map((n) => pickVoiceLine(bank, 'a', 'Y', n).file), ['a1y.ogg', 'a3y.ogg', 'a1y.ogg']);
  assert.deepEqual(pickVoiceLine(bank, 'a', 'Y', 1), { greek: 'Γ', en: 'a3', file: 'a3y.ogg', dur: 3.1 });
  assert.equal(variantCount(bank, 'a', 'X'), 3);
  assert.equal(variantCount(bank, 'a', 'Y'), 2);
  assert.equal(variantCount(bank, 'a', 'Z'), 0);
  assert.equal(pickVoiceLine(bank, 'a', 'Z', 0), null);
  assert.equal(pickVoiceLine(bank, 'nope', 'X', 0), null);
  assert.equal(pickVoiceLine(null, 'a', 'X', 0), null);
  // Odd counters still land on a variant.
  assert.equal(pickVoiceLine(bank, 'a', 'X', -1).file, 'a3x.ogg');
  assert.equal(pickVoiceLine(bank, 'a', 'X', NaN).file, 'a1x.ogg');
  assert.equal(pickVoiceLine(bank, 'a', 'X', 4.7).file, 'a2x.ogg');
  assert.deepEqual(clipFiles(bank, ['a', 'nope'], ['Y']), ['a1y.ogg', 'a3y.ogg']);
  assert.deepEqual(clipFiles(bank, ['a'], ['X', 'Y']), ['a1x.ogg', 'a1y.ogg', 'a2x.ogg', 'a3x.ogg', 'a3y.ogg']);
});

test('the bank is frozen data with the generated header', () => {
  const src = fs.readFileSync(path.join(GAME, 'js/audio/voicebank.js'), 'utf8');
  assert.ok(src.startsWith('// GENERATED by spartan/tools/voice/render.py from spartan/tools/voice/lines.json. Do not edit by hand.\n'));
  assert.ok(Object.isFrozen(VOICEBANK));
  for (const list of Object.values(VOICEBANK)) {
    assert.ok(Object.isFrozen(list) && list.length > 0);
    for (const v of list) assert.ok(Object.isFrozen(v) && Object.isFrozen(v.clips) && Object.values(v.clips).every(Object.isFrozen));
  }
});

test('every clip is a mono Ogg Opus file on disk whose dur matches its real length', () => {
  const clips = allClips();
  assert.ok(clips.length >= 29, `${clips.length} clips`);
  for (const c of clips) {
    const where = `${c.key}#${c.i + 1} ${c.speaker}`;
    assert.match(c.file, /^audio\/voice\/[\w.-]+\.ogg$/, `${where}: ${c.file}`);
    const full = path.join(GAME, c.file);
    assert.ok(fs.existsSync(full), `${where}: ${c.file} is missing`);
    const o = oggOpus(fs.readFileSync(full));
    assert.ok(o.head && o.tags, `${where}: OpusHead/OpusTags`);
    assert.equal(o.version, 1, `${where}: OpusHead version`);
    assert.equal(o.channels, 1, `${where}: mono`);
    const real = Number(o.lastGranule - BigInt(o.preSkip)) / 48000;
    assert.ok(Number.isFinite(c.dur) && c.dur > 0.3 && c.dur < 12, `${where}: dur ${c.dur}`);
    assert.ok(Math.abs(c.dur - real) <= 0.1, `${where}: dur ${c.dur} s but the file plays ${real.toFixed(3)} s`);
  }
  // No clip on disk that the bank doesn't use (they would only bloat the APK).
  const used = new Set(clips.map((c) => path.basename(c.file)));
  const extra = fs.readdirSync(VOICE_DIR).filter((f) => !used.has(f));
  assert.deepEqual(extra, [], 'unused files in audio/voice');
});

test('every Greek line has clips for everyone who can say it; the Narrator stays text-to-speech', () => {
  for (const [key, v] of Object.entries(VOICE)) {
    if (v.speaker === 'Narrator') {
      assert.equal(VOICEBANK[key], undefined, `${key}: the Narrator speaks English (TTS)`);
      continue;
    }
    assert.ok(VOICEBANK[key], `${key} has no recorded lines`);
    for (const sp of speakersOf(key)) assert.ok(variantCount(VOICEBANK, key, sp) > 0, `${key}: no clip for ${sp}`);
  }
  for (const [key, list] of Object.entries(VOICEBANK)) {
    assert.ok(VOICE[key], `${key} is not a campaign line`);
    for (const v of list) {
      for (const sp of Object.keys(v.clips)) assert.ok(speakersOf(key).includes(sp), `${key}: ${sp} never says it`);
    }
  }
  // Frequent barks have several wordings so they don't repeat.
  for (const [key, n] of Object.entries({ holdTheLine: 3, shieldsUp: 3, warcry: 2, respite: 2 })) {
    for (const sp of speakersOf(key)) assert.ok(variantCount(VOICEBANK, key, sp) >= n, `${key}: ${sp} has fewer than ${n} variants`);
  }
});

test('Greek is in epigraphic capitals without diacritics, with an English subtitle', () => {
  // Capitals Α–Ω (U+0391–U+03A9, no final ς), a word may end in an elision mark (’ or '), words
  // parted by spaces and stops: , . ; · (U+00B7 or U+0387) ⁝
  const W = "[\\u0391-\\u03A1\\u03A3-\\u03A9]+[\\u2019\\u02BC']?";
  const GREEK = new RegExp(`^${W}(?:[ ,.;\\u00B7\\u0387\\u205D]+${W})*[,.;\\u00B7\\u0387\\u205D]?$`, 'u');
  for (const [key, list] of Object.entries(VOICEBANK)) {
    list.forEach((v, i) => {
      assert.match(v.greek, GREEK, `${key}#${i + 1}: ${v.greek}`);
      assert.ok(!/\p{M}/u.test(v.greek.normalize('NFD')), `${key}#${i + 1}: no accents or breathings`);
      assert.ok(typeof v.en === 'string' && v.en.trim().length > 1, `${key}#${i + 1}: English subtitle`);
    });
  }
  assert.equal(VOICEBANK.molonLabe[0].greek, 'ΜΟΛΩΝ ΛΑΒΕ');
});
